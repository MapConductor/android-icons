#!/usr/bin/env node

import { access, mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const androidIconsRepository = path.resolve(scriptDirectory, '..');
const androidSdkRoot = path.dirname(androidIconsRepository);
const mapConductorRoot = path.dirname(androidSdkRoot);
const iosSdkRoot = path.join(mapConductorRoot, 'ios-sdk');
const reactSdkRoot = path.join(mapConductorRoot, 'react-sdk');
const checkOnly = process.argv.includes('--check');
const selectedPackArgument = process.argv.find((argument) => argument.startsWith('--pack='));
const selectedPack = selectedPackArgument?.slice('--pack='.length);
const generatedHeader = '// Generated by android-icons/scripts/generate-icon-packs.mjs. Do not edit.\n';

const exists = async (target) => {
  try {
    await access(target);
    return true;
  } catch {
    return false;
  }
};

const fail = (message) => {
  throw new Error(message);
};

const readManifests = async () => {
  const entries = await readdir(androidSdkRoot, { withFileTypes: true });
  const manifestPaths = [];
  for (const entry of entries) {
    if (!entry.isDirectory() || (entry.name !== 'android-icons' && !entry.name.startsWith('android-icons-'))) {
      continue;
    }
    const manifestPath = path.join(androidSdkRoot, entry.name, 'artwork', 'manifest.json');
    if (await exists(manifestPath)) manifestPaths.push(manifestPath);
  }

  const manifests = [];
  for (const manifestPath of manifestPaths.sort()) {
    const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
    manifest.manifestPath = manifestPath;
    manifest.artworkDirectory = path.dirname(manifestPath);
    validateManifest(manifest);
    if (!selectedPack || selectedPack === manifest.id) manifests.push(manifest);
  }
  if (selectedPack && manifests.length === 0) fail(`Unknown icon pack: ${selectedPack}`);
  return manifests;
};

const validateManifest = (manifest) => {
  if (manifest.schemaVersion !== 1) fail(`${manifest.manifestPath}: unsupported schemaVersion`);
  for (const key of ['id', 'collection']) {
    if (typeof manifest[key] !== 'string' || manifest[key].length === 0) {
      fail(`${manifest.manifestPath}: ${key} is required`);
    }
  }
  for (const platform of ['android', 'ios', 'react']) {
    if (!manifest[platform]?.repository) fail(`${manifest.manifestPath}: ${platform}.repository is required`);
  }
  if (!manifest.android.namespace) fail(`${manifest.manifestPath}: android.namespace is required`);
  if (!manifest.ios.module) fail(`${manifest.manifestPath}: ios.module is required`);
  if (!Array.isArray(manifest.icons) || manifest.icons.length === 0) {
    fail(`${manifest.manifestPath}: icons must not be empty`);
  }
  const names = new Set();
  const identifiers = new Set();
  for (const icon of manifest.icons) {
    if (!/^[a-z][A-Za-z0-9]*$/.test(icon.name)) fail(`${manifest.manifestPath}: invalid name ${icon.name}`);
    if (!/^[a-z0-9]+(?:[._][a-z0-9]+)*$/.test(icon.id)) fail(`${manifest.manifestPath}: invalid ID ${icon.id}`);
    if (manifest.id !== 'common' && !icon.id.startsWith(`${manifest.id}.`)) {
      fail(`${manifest.manifestPath}: ${icon.id} must use the ${manifest.id}. namespace`);
    }
    if (names.has(icon.name)) fail(`${manifest.manifestPath}: duplicate name ${icon.name}`);
    if (identifiers.has(icon.id)) fail(`${manifest.manifestPath}: duplicate ID ${icon.id}`);
    names.add(icon.name);
    identifiers.add(icon.id);
  }
};

const loadIcons = async (manifest) => {
  const icons = [];
  for (const icon of manifest.icons) {
    const svgPath = path.join(manifest.artworkDirectory, icon.file);
    const svg = await readFile(svgPath, 'utf8');
    if (!/viewBox=["']0 0 24 24["']/.test(svg)) fail(`${svgPath}: viewBox must be 0 0 24 24`);
    const paths = [...svg.matchAll(/<path\b[^>]*\bd=["']([^"']+)["'][^>]*>/g)].map((match) => match[1].trim());
    if (paths.length !== 1) fail(`${svgPath}: exactly one path element is required`);
    icons.push({ ...icon, pathData: paths[0], commands: parsePath(paths[0], svgPath) });
  }
  return icons;
};

const parsePath = (pathData, source) => {
  const tokenPattern = /[MLCZ]|-?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?/g;
  const tokens = pathData.match(tokenPattern) ?? [];
  const remainder = pathData.replace(tokenPattern, '').replace(/[\s,]/g, '');
  if (remainder.length > 0) fail(`${source}: unsupported SVG path content: ${remainder}`);
  const commands = [];
  let index = 0;
  const number = () => {
    const token = tokens[index++];
    if (token === undefined || /^[MLCZ]$/.test(token)) fail(`${source}: expected a number near token ${index}`);
    return token;
  };
  while (index < tokens.length) {
    const command = tokens[index++];
    if (command === 'M' || command === 'L') {
      commands.push({ command, values: [number(), number()] });
    } else if (command === 'C') {
      commands.push({ command, values: [number(), number(), number(), number(), number(), number()] });
    } else if (command === 'Z') {
      commands.push({ command, values: [] });
    } else {
      fail(`${source}: only absolute M, L, C and Z commands are supported (found ${command})`);
    }
  }
  return commands;
};

const kotlinSource = (manifest, icons) => {
  const properties = icons.map((icon) => [
    `    /** ${icon.description}. */`,
    `    val ${icon.name} =`,
    '        MapIconGlyph(',
    `            id = "${icon.id}",`,
    `            pathData = "${icon.pathData}",`,
    '        )',
  ].join('\n')).join('\n\n');
  const glyphImport = manifest.id === 'common' ? '' : 'import com.mapconductor.icons.MapIconGlyph\n\n';
  return `${generatedHeader}package ${manifest.android.namespace}\n\n${glyphImport}/** ${manifest.id === 'common' ? 'Common, region-neutral' : `${manifest.id} pack`} map symbols. Selection is always explicit. */\nobject ${manifest.collection} {\n${properties}\n}\n`;
};

const swiftCommand = ({ command, values }) => {
  const point = (x, y) => `CGPoint(x: ${x}, y: ${y})`;
  if (command === 'M') return `.moveTo(${point(values[0], values[1])})`;
  if (command === 'L') return `.lineTo(${point(values[0], values[1])})`;
  if (command === 'C') {
    return `.curveTo(end: ${point(values[4], values[5])}, control1: ${point(values[0], values[1])}, control2: ${point(values[2], values[3])})`;
  }
  return '.close';
};

const swiftSource = (manifest, icons) => {
  const properties = icons.map((icon) => {
    const commands = icon.commands.map((command) => `            ${swiftCommand(command)},`).join('\n');
    return [
      `    /// ${icon.description}.`,
      `    public static let ${icon.name} = MapIconGlyph(`,
      `        id: "${icon.id}",`,
      '        commands: [',
      commands,
      '        ]',
      '    )',
    ].join('\n');
  }).join('\n\n');
  const glyphImport = manifest.id === 'common' ? '' : 'import MapConductorIcons\n';
  return `${generatedHeader}import CoreGraphics\n${glyphImport}\n/// Map symbols from the ${manifest.id} pack. Selection is always explicit.\npublic enum ${manifest.collection} {\n${properties}\n}\n`;
};

const typeScriptSource = (manifest, icons) => {
  const properties = icons.map((icon) => [
    `  /** ${icon.description}. */`,
    `  ${icon.name}: {`,
    `    id: '${icon.id}',`,
    `    pathData: '${icon.pathData}',`,
    '    viewBoxSize: 24,',
    '  },',
  ].join('\n')).join('\n');
  const glyphImport = manifest.id === 'common'
    ? "import type { MapIconGlyph } from './MapIconGlyph';"
    : "import type { MapIconGlyph } from '@mapconductor/react-icons';";
  return `${generatedHeader}${glyphImport}\n\n/** Map symbols from the ${manifest.id} pack. Selection is always explicit. */\nexport const ${manifest.collection} = {\n${properties}\n} as const satisfies Record<string, MapIconGlyph>;\n`;
};

const outputsFor = (manifest, icons) => {
  const androidPackagePath = manifest.android.namespace.split('.').join(path.sep);
  return [
    {
      platform: 'android',
      file: path.join(androidSdkRoot, manifest.android.repository, 'src', 'main', 'java', androidPackagePath, `${manifest.collection}.kt`),
      content: kotlinSource(manifest, icons),
    },
    {
      platform: 'ios',
      file: path.join(iosSdkRoot, manifest.ios.repository, 'Sources', manifest.ios.module, `${manifest.collection}.swift`),
      content: swiftSource(manifest, icons),
    },
    {
      platform: 'react',
      file: path.join(reactSdkRoot, manifest.react.repository, 'src', `${manifest.collection}.ts`),
      content: typeScriptSource(manifest, icons),
    },
  ];
};

const writeOrCheck = async ({ platform, file, content }) => {
  if (checkOnly) {
    const existing = await readFile(file, 'utf8').catch(() => null);
    if (existing !== content) return `${platform}: ${file}`;
    return null;
  }
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, content);
  return null;
};

const main = async () => {
  const manifests = await readManifests();
  const globalIdentifiers = new Set();
  const changed = [];
  let iconCount = 0;
  for (const manifest of manifests) {
    const icons = await loadIcons(manifest);
    iconCount += icons.length;
    for (const icon of icons) {
      if (globalIdentifiers.has(icon.id)) fail(`Duplicate global glyph ID: ${icon.id}`);
      globalIdentifiers.add(icon.id);
    }
    for (const output of outputsFor(manifest, icons)) {
      const difference = await writeOrCheck(output);
      if (difference) changed.push(difference);
    }
  }
  if (changed.length > 0) {
    console.error('Generated icon sources are out of date:');
    for (const difference of changed) console.error(`- ${difference}`);
    process.exitCode = 1;
    return;
  }
  console.log(`${checkOnly ? 'Checked' : 'Generated'} ${iconCount} glyphs across ${manifests.length} packs and 3 SDKs.`);
};

await main();
